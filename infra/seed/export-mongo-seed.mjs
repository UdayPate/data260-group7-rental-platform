// Turns the frontend's mock threads, messages and reviews (frontend/src/mocks/data/*.ts) into
// infra/mongo/seed.json for the Messaging and Review services (Himja), the same way
// export-mock-seed.mjs makes the MySQL seed: same ids, same text, dates kept RELATIVE to today
// ({"$dt": 6} = 6 days ago), turned into real datetimes when the services load the seed.
//
// Run (needs `npm install` once in frontend/ so that esbuild exists):
//     node infra/seed/export-mongo-seed.mjs
import { createRequire } from 'node:module'
import { mkdtempSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(here, '../..')
const mocks = path.join(root, 'frontend/src/mocks')
const require = createRequire(path.join(root, 'frontend/package.json'))
let esbuild
try { esbuild = require('esbuild') } catch { esbuild = createRequire(import.meta.url)('esbuild') }

// Stand-in for mocks/dates.ts: markers instead of real dates.
const stubDir = mkdtempSync(path.join(tmpdir(), 'xenia-mongo-seed-'))
const stub = path.join(stubDir, 'dates.js')
writeFileSync(stub, `
export const daysFromToday = (n) => ({ $date: n })
export const daysAgoDatetime = (n) => ({ $dt: n })
export const today = () => ({ $date: 0 })
export const nowDatetime = () => ({ $dt: 0 })
export const nightsBetween = () => 0
export const rangesOverlap = () => false
export const isValidDate = () => true
`)
const imp = (n) => JSON.stringify(path.join(mocks, 'data', n))
const entry = path.join(stubDir, 'entry.ts')
writeFileSync(entry, `
import { seedHosts } from ${imp('hosts.ts')}
import { seedGuests } from ${imp('guests.ts')}
import { seedProperties } from ${imp('properties.ts')}
import { seedThreads, seedMessages } from ${imp('threads.ts')}
import { seedReviews } from ${imp('reviews.ts')}
import { pastStayReviews } from ${imp('pastStays.ts')}
export default { seedHosts, seedGuests, seedProperties, seedThreads, seedMessages, seedReviews, pastStayReviews }
`)
const out = path.join(stubDir, 'bundle.mjs')
await esbuild.build({
  entryPoints: [entry], bundle: true, format: 'esm', outfile: out, platform: 'node', logLevel: 'error',
  plugins: [{ name: 'stub-dates', setup(build) { build.onResolve({ filter: /(^|\/)dates$/ }, () => ({ path: stub })) } }],
})
const data = (await import(pathToFileURL(out).href)).default

const guestName = (id) => {
  const g = data.seedGuests.find((x) => x.guest_id === id)
  return `${g.first_name} ${g.last_name}`
}
// Names are copied in, exactly like the mock's db.ts and like the real services do at open/create time.
const threads = data.seedThreads.map((t) => ({
  ...t,
  guest_name: guestName(t.guest_id),
  host_name: data.seedHosts.find((h) => h.host_id === t.host_id).name,
  property_title: data.seedProperties.find((p) => p.property_id === t.property_id).title,
}))
const reviews = [...data.seedReviews, ...data.pastStayReviews].map((r) => ({ ...r, guest_name: guestName(r.guest_id) }))

const file = path.join(root, 'infra/mongo/seed.json')
writeFileSync(file, JSON.stringify({
  _comment: 'GENERATED by infra/seed/export-mongo-seed.mjs from frontend/src/mocks/data. {"$dt": n} = n days ago.',
  threads, messages: data.seedMessages, reviews,
}, null, 1) + '\n')
console.log(`wrote ${file}: ${threads.length} threads, ${data.seedMessages.length} messages, ${reviews.length} reviews`)
