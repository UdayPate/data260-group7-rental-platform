// Turns the frontend's mock seed data (frontend/src/mocks/data/*.ts) into infra/mysql/03_seed.sql,
// so the real database starts with EXACTLY the same ids and values as the mocks.
//
// Why a generator and not a hand-copy: Uday owns the mocks. If he changes a mock listing, run this
// again and the database follows. The dates in the mocks are "relative to today" (daysFromToday(10)),
// so the generated SQL keeps them relative too: UTC_DATE() + 10 days, worked out when the SQL runs.
//
// Run (needs `npm install` once in frontend/ so that esbuild exists):
//     node infra/seed/export-mock-seed.mjs
import { createRequire } from 'node:module'
import { mkdtempSync, writeFileSync, readFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(here, '../..')
const mocks = path.join(root, 'frontend/src/mocks')

// esbuild comes with Vite, so it is in frontend/node_modules after `npm install`.
const require = createRequire(path.join(root, 'frontend/package.json'))
let esbuild
try { esbuild = require('esbuild') } catch { esbuild = createRequire(import.meta.url)('esbuild') }

// A stand-in for mocks/dates.ts: instead of real dates it returns markers like { $date: 10 },
// which we turn into SQL further down.
const stubDir = mkdtempSync(path.join(tmpdir(), 'xenia-dates-'))
const stub = path.join(stubDir, 'dates.js')
writeFileSync(stub, `
export const daysFromToday = (n) => ({ $date: n })
export const daysAgoDatetime = (n) => ({ $dt: n })
export const today = () => ({ $date: 0 })
export const nowDatetime = () => ({ $dt: 0 })
export const nightsBetween = () => 0
export const rangesOverlap = () => false
export const isValidDate = () => true
`)

const entry = path.join(stubDir, 'entry.ts')
const imp = (n) => JSON.stringify(path.join(mocks, 'data', n))
writeFileSync(entry, `
import { seedHosts } from ${imp('hosts.ts')}
import { seedGuests } from ${imp('guests.ts')}
import { seedProperties } from ${imp('properties.ts')}
import { seedReservations } from ${imp('reservations.ts')}
import { pastStayReservations } from ${imp('pastStays.ts')}
import { seedHostBlocks } from ${imp('availability.ts')}
import { seedSaved } from ${imp('saved.ts')}
import { seedAccounts } from ${imp('accounts.ts')}
export default { seedHosts, seedGuests, seedProperties, seedReservations, pastStayReservations, seedHostBlocks, seedSaved, seedAccounts }
`)

const out = path.join(stubDir, 'bundle.mjs')
await esbuild.build({
  entryPoints: [entry], bundle: true, format: 'esm', outfile: out, platform: 'node', logLevel: 'error',
  plugins: [{
    name: 'stub-dates',
    setup(build) { build.onResolve({ filter: /(^|\/)dates$/ }, () => ({ path: stub })) },
  }],
})
const data = (await import(pathToFileURL(out).href)).default

// ---------- SQL helpers ----------
const q = (s) => (s === null || s === undefined ? 'NULL' : `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "''")}'`)
const isDate = (v) => v && typeof v === 'object' && '$date' in v
const isDt = (v) => v && typeof v === 'object' && '$dt' in v
const dateSql = (v) => `DATE_ADD(UTC_DATE(), INTERVAL ${v.$date} DAY)`
const dtSql = (v) => `DATE_SUB(UTC_TIMESTAMP(3), INTERVAL ${v.$dt} DAY)`
const val = (v) => (isDate(v) ? dateSql(v) : isDt(v) ? dtSql(v) : typeof v === 'number' ? String(v) : q(v))
const json = (v) => q(JSON.stringify(v))
const insert = (table, cols, rows) =>
  rows.length ? `INSERT INTO ${table} (${cols.join(', ')}) VALUES\n${rows.map((r) => '  (' + r.join(', ') + ')').join(',\n')};\n\n` : ''

let sql = `-- GENERATED by infra/seed/export-mock-seed.mjs from frontend/src/mocks/data/*.ts. Do not edit by hand.
-- Same ids and values as the frontend mocks. Dates are relative to the day this script runs.
-- Safe to run again: it empties the seeded tables first (infra/seed/reseed.sh does exactly that).

SET NAMES utf8mb4;
SET time_zone = '+00:00';
SET FOREIGN_KEY_CHECKS = 0;
DELETE FROM processed_events;
DELETE FROM idempotency_keys;
DELETE FROM reservation_status_history;
DELETE FROM reservations;
DELETE FROM availability_nights;
DELETE FROM availability_blocks;
DELETE FROM saved_properties;
DELETE FROM properties;
DELETE FROM accounts;
DELETE FROM guests;
DELETE FROM hosts;
DELETE FROM id_counters;
SET FOREIGN_KEY_CHECKS = 1;

`

// hosts
sql += insert('hosts', ['host_id','name','email','phone','profile_photo_url','verification_status','response_rate','response_time','host_since','access_level'],
  data.seedHosts.map((h) => [q(h.host_id), q(h.name), q(h.email), q(h.phone), q(h.profile_photo_url), q(h.verification_status), val(h.response_rate), val(h.response_time), val(h.host_since), q(h.access_level)]))

// guests (counters are counted on read, so they are not columns)
sql += insert('guests', ['guest_id','first_name','last_name','email','phone','location','profile_photo_url','preferences','profile_created_datetime'],
  data.seedGuests.map((g) => [q(g.guest_id), q(g.first_name), q(g.last_name), q(g.email), q(g.phone), q(g.location), q(g.profile_photo_url), json(g.preferences), val(g.profile_created_datetime)]))

// accounts: every demo account has the same bcrypt hash of "demo1234"
sql += insert('accounts', ['email','password_hash','role','user_id'],
  data.seedAccounts.map((a) => [q(a.email), q(a.password_hash), q(a.role), q(a.user_id)]))

// properties
const propById = Object.fromEntries(data.seedProperties.map((p) => [p.property_id, p]))
sql += insert('properties', ['property_id','host_id','title','description','property_type','address','city','state','zip_code','latitude','longitude','capacity','bedrooms','bathrooms','amenities','nightly_price','cleaning_fee','status','rating','review_count','created_datetime','photo_url'],
  data.seedProperties.map((p) => [q(p.property_id), q(p.host_id), q(p.title), q(p.description), q(p.property_type), q(p.address), q(p.city), q(p.state), q(p.zip_code), val(p.latitude), val(p.longitude), val(p.capacity), val(p.bedrooms), val(p.bathrooms), json(p.amenities), val(p.nightly_price), val(p.cleaning_fee), q(p.status), val(p.rating), val(p.review_count), val(p.created_datetime), q(p.photo_url ?? '')]))

// saved properties (the mock gives the i-th save a time of 2 + i*4 days ago)
sql += insert('saved_properties', ['guest_id','property_id','saved_datetime'],
  data.seedSaved.map((s, i) => [q(s.guest_id), q(s.property_id), dtSql({ $dt: 2 + i * 4 })]))

// reservations: 24 seed + 40 older completed stays, with the price worked out like db.ts priceBreakdown()
const reservations = [...data.seedReservations, ...data.pastStayReservations]
const traceId = (id) => `5eed0000-0000-4000-8000-${id.replace(/\D/g, '').padStart(12, '0')}`
sql += insert('reservations', ['reservation_id','trace_id','property_id','guest_id','check_in','check_out','guest_count','nights','nightly_price','subtotal','cleaning_fee','total','booking_datetime','status','cancellation_reason','failure_code','guest_message','updated_datetime'],
  reservations.map((r) => {
    const p = propById[r.property_id]
    const nights = r.check_out.$date - r.check_in.$date
    const subtotal = nights * p.nightly_price
    return [q(r.reservation_id), q(traceId(r.reservation_id)), q(r.property_id), q(r.guest_id), val(r.check_in), val(r.check_out), val(r.guest_count), String(nights), val(p.nightly_price), String(subtotal), val(p.cleaning_fee), String(subtotal + p.cleaning_fee), val(r.booking_datetime), q(r.status), q(r.cancellation_reason), 'NULL', q(r.guest_message), val(r.booking_datetime)]
  }))

// first history row of every seed reservation
sql += insert('reservation_status_history', ['reservation_id','old_status','new_status','actor_id','trace_id','note','changed_at'],
  reservations.map((r) => [q(r.reservation_id), 'NULL', q(r.status), q('seed'), q(traceId(r.reservation_id)), q('Seed data'), val(r.booking_datetime)]))

// availability: the host blocks, then one "booked" block for every pending or approved reservation (like db.ts)
const blocks = data.seedHostBlocks.map((b) => ({ ...b, reservation_id: null }))
let nextA = Math.max(...blocks.map((b) => Number(b.availability_id.split('_')[1]))) + 1
for (const r of reservations.filter((x) => x.status === 'pending' || x.status === 'approved')) {
  blocks.push({ availability_id: `a_${String(nextA++).padStart(3, '0')}`, property_id: r.property_id, start_date: r.check_in, end_date: r.check_out, status: 'booked', source: 'booking', updated_datetime: r.booking_datetime, reservation_id: r.reservation_id })
}
sql += insert('availability_blocks', ['availability_id','property_id','start_date','end_date','status','source','reservation_id','updated_datetime'],
  blocks.map((b) => [q(b.availability_id), q(b.property_id), val(b.start_date), val(b.end_date), q(b.status), q(b.source), q(b.reservation_id), val(b.updated_datetime)]))
const nights = []
for (const b of blocks) for (let d = b.start_date.$date; d < b.end_date.$date; d++) nights.push([q(b.property_id), dateSql({ $date: d }), q(b.availability_id)])
sql += insert('availability_nights', ['property_id','night_date','availability_id'], nights)

// next ids to hand out
const maxNum = (ids) => Math.max(...ids.map((i) => Number(i.split('_')[1])))
sql += insert('id_counters', ['prefix','next_value'], [
  [q('g'), String(maxNum(data.seedGuests.map((g) => g.guest_id)) + 1)],
  [q('h'), String(maxNum(data.seedHosts.map((h) => h.host_id)) + 1)],
  [q('p'), String(maxNum(data.seedProperties.map((p) => p.property_id)) + 1)],
  [q('r'), String(maxNum(reservations.map((r) => r.reservation_id)) + 1)],
  [q('a'), String(nextA)],
])

const target = path.join(root, 'infra/mysql/03_seed.sql')
writeFileSync(target, sql)
console.log(`wrote ${path.relative(root, target)}: ${data.seedHosts.length} hosts, ${data.seedGuests.length} guests, ${data.seedProperties.length} properties, ${reservations.length} reservations, ${blocks.length} blocks, ${nights.length} nights, ${data.seedAccounts.length} accounts`)
